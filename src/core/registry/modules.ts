export function getDomainById(id: string): DomainDefinition | undefined {
  return DOMAINS.find((d) => d.id === id);
}

export function getCenterById(id: string): CenterDefinition | undefined {
  return CENTERS.find((c) => c.id === id);
}

export function getCentersByDomain(domainId: string): CenterDefinition[] {
  return CENTERS.filter((center) => center.domainId === domainId && MODULES.some((mod) => mod.centerId === center.id));
}

export function getModuleById(id: string): ModuleDefinition | undefined {
  return MODULES.find((m) => m.id === id);
}

export function getModulesByCenter(centerId: string): ModuleDefinition[] {
  return MODULES.filter((m) => m.centerId === centerId);
}

export function getModulesByDomain(domainId: string): ModuleDefinition[] {
  const centerIds = new Set(getCentersByDomain(domainId).map((c) => c.id));
  return MODULES.filter((m) => centerIds.has(m.centerId));
}
